export function firmwareIno(sensor: Record<string, unknown>, opts: { mcu: string; sensor: string; wifiSsid: string; wifiPass: string; baseUrl: string; apiKey: string; intervalSeconds: number }) {
  const codeId = String(sensor.sensor_code || sensor.id || 'sensor');
  const cleanBase = opts.baseUrl.endsWith('/') ? opts.baseUrl.slice(0, -1) : opts.baseUrl;
  const filename = `${codeId}_${opts.mcu}_${opts.sensor}.ino`.replace(/[^A-Za-z0-9_.-]/g, '_');
  const code = `// Auto-generated by SynapseCity (TS reference)\n// Sensor ${codeId} | MCU ${opts.mcu} | ${opts.sensor}\n#include <WiFi.h>\n#include <HTTPClient.h>\n#include <WiFiClientSecure.h>\n#define WIFI_SSID "${opts.wifiSsid}"\n#define WIFI_PASS "${opts.wifiPass}"\n#define CITY_BASE_URL "${cleanBase}"\n#define SENSOR_ID "${codeId}"\n#define API_KEY "${opts.apiKey}"\n// loop: read sensor -> POST CITY_BASE_URL/v1/iot/sensors/SENSOR_ID/data every ${opts.intervalSeconds}s\nvoid setup(){Serial.begin(115200);WiFi.begin(WIFI_SSID,WIFI_PASS);}\nvoid loop(){delay(${opts.intervalSeconds * 1000});}\n`;
  return { filename, language: 'arduino', code, mcu: opts.mcu, sensor: opts.sensor, interval_seconds: opts.intervalSeconds };
}
